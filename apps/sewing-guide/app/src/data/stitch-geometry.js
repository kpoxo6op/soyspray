// Needle paths for all 100 stitches of the passport 3.0. Utility stitches follow the real
// needle sequence; decorative motifs are drawn to match the pull-out stitch card and are
// marked approximate in the UI. Units: x in half-widths (-1..1), y in stitch lengths.

const line = (pts) => ({ kind: 'line', pts });
const satin = (period, left, right, step = 0.4, defaultLength = 0.4) => ({ kind: 'satin', period, left, right, step, defaultLength });
const motif = (strokes, h, defaultLength = 2.5) => ({ kind: 'motif', strokes, h, defaultLength });

const zig = (n, x0 = -1, x1 = 1) => Array.from({ length: n }, (_, i) => [i % 2 ? x1 : x0, 1]);
const seg = (x0, y0, x1, y1, n = 2) => Array.from({ length: n }, (_, i) => [x0 + ((x1 - x0) * i) / (n - 1), y0 + ((y1 - y0) * i) / (n - 1)]);
const circle = (cx, cy, r, n = 16, ry = r) => Array.from({ length: n + 1 }, (_, i) => [cx + r * Math.cos((i / n) * Math.PI * 2), cy + ry * Math.sin((i / n) * Math.PI * 2)]);
const wave = (x0, x1, y0, y1, amp, n = 12, phase = 0) =>
  Array.from({ length: n + 1 }, (_, i) => {
    const t = i / n;
    return [x0 + (x1 - x0) * t + amp * Math.sin(phase + t * Math.PI * 2), y0 + (y1 - y0) * t];
  });
const cross = (cx, cy, r) => [seg(cx - r, cy - r, cx + r, cy + r), seg(cx + r, cy - r, cx - r, cy + r)];
const plus = (cx, cy, r) => [seg(cx - r, cy, cx + r, cy), seg(cx, cy - r, cx, cy + r)];
const star = (cx, cy, r) => [...plus(cx, cy, r), ...cross(cx, cy, r * 0.72)];
const leaf = (x0, y0, x1, y1, bulge) => {
  const dx = x1 - x0;
  const dy = y1 - y0;
  const len = Math.hypot(dx, dy) || 1;
  const nx = (-dy / len) * bulge;
  const ny = (dx / len) * bulge;
  const pts = [];
  for (let i = 0; i <= 10; i++) {
    const t = i / 10;
    const b = Math.sin(t * Math.PI);
    pts.push([x0 + dx * t + nx * b, y0 + dy * t + ny * b]);
  }
  for (let i = 10; i >= 0; i--) {
    const t = i / 10;
    const b = Math.sin(t * Math.PI);
    pts.push([x0 + dx * t - nx * b, y0 + dy * t - ny * b]);
  }
  return pts;
};
const scallop = (t) => Math.abs(Math.sin(t * Math.PI));

// Buttonholes: two satin columns with a bartack at each end, drawn as one motif of h mm.
function buttonhole(kind) {
  const strokes = [];
  const col = (x, y0, y1, open) => {
    const pts = [];
    const n = open ? 14 : 44;
    for (let i = 0; i <= n; i++) pts.push([i % 2 ? x - 0.42 : x, y0 + ((y1 - y0) * i) / n]);
    strokes.push(pts);
  };
  const tack = (y) => {
    const pts = [];
    for (let i = 0; i <= 8; i++) pts.push([i % 2 ? -1 : 1, y + (i / 8) * 0.04]);
    strokes.push(pts);
  };
  col(-0.55, 0.08, 0.92, kind === 'stretch');
  col(1, 0.08, 0.92, kind === 'stretch');
  if (kind === 'rounded') strokes.push(circle(0.2, 0.08, 0.6, 12, 0.07).slice(6));
  else tack(0.03);
  if (kind === 'eyelet') strokes.push(circle(0.2, 0.9, 0.75, 14, 0.09));
  else tack(0.93);
  return motif(strokes, 16, 0.4);
}

